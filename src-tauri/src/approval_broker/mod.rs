//! `approval_broker`: approvals and clarifications asked by a tool that runs
//! inside a CLI chat turn (contract C2 of the change
//! `cli-substitui-agente-nativo`, `openspec/changes/cli-substitui-agente-nativo/design.md`).
//!
//! A tool calls [`ApprovalBroker::request`] with the turn it belongs to. The
//! broker records the same `interruption` item the native engine records
//! (with `engine: "cli"`), moves the run to `waiting_for_user`, emits
//! `interruption.requested` on `clovy://agent-runtime-event` so the existing
//! approval and clarification cards render, and waits for one decision:
//!
//! - the desktop answers through `resolve_agent_interruption`, which hands
//!   items with `engine: "cli"` to [`commands::resolve_cli_interruption`];
//! - nobody answers within the timeout: `approval_timed_out`, item `expired`;
//! - the run ends or the app closes: `run_cancelled`, item `cancelled`;
//! - an unattended turn (routines) is denied at once with
//!   `unattended_requires_approval`, without a card.
//!
//! Exactly one decision counts: whoever removes the request's waiter from the
//! in-memory table owns the outcome, and the item only leaves `pending` once
//! (`store::settle`). Pending CLI items left by a previous process are
//! cancelled at startup ([`setup`]).

