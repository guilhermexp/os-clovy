/// How long a request waits for the user. Always shorter than the MCP tool
/// timeout the turn passes to the CLI (`design.md` §3: 15 minutes), so the
/// CLI receives the broker's answer instead of its own timeout.
pub const APPROVAL_TIMEOUT: Duration = Duration::from_secs(10 * 60);

/// Marks an interruption item as asked by a CLI turn through the broker.
pub const CLI_ENGINE: &str = "cli";

/// The turn a request belongs to, as plain values (the MCP turn binding,
/// `TurnBinding`, maps onto this).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ApprovalTurn {
    pub session_id: String,
    pub run_id: String,
    /// The CLI id (`claude`, `codex`, ...).
    pub cli: String,
    pub safety_mode: AgentSafetyMode,
    /// `false` for turns no person is watching (routines).
    pub attended: bool,
}

impl From<&crate::mcp_server::turns::TurnBinding> for ApprovalTurn {
    /// The turn of a bound MCP connection (`ToolCtx::binding`).
    fn from(binding: &crate::mcp_server::turns::TurnBinding) -> Self {
        Self {
            session_id: binding.session_id.clone(),
            run_id: binding.run_id.clone(),
            cli: binding.cli.id().to_string(),
            safety_mode: binding.safety_mode,
            attended: binding.attended,
        }
    }
}

/// What a tool asks the user.
#[derive(Clone, Debug)]
pub struct ApprovalRequest {
    /// The Clovy tool name, as listed by the MCP server.
    pub tool: String,
    /// The CLI's tool call id, when the tool knows it.
    pub call_id: Option<String>,
    pub kind: ApprovalKind,
}

#[derive(Clone, Debug)]
pub enum ApprovalKind {
    /// Approve or deny one tool call. `title` and `description` are written
    /// by the tool's own code (never model text); the card's command line is
    /// generated by the broker from `preview`, or else from the arguments,
    /// sanitized.
    Approval {
        title: String,
        description: String,
        arguments: Value,
        preview: Option<String>,
    },
    /// Ask a question; the answer is the tool result.
    Clarification {
        question: String,
        choices: Vec<String>,
    },
}

/// A decision that lets the tool continue.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ApprovalOutcome {
    /// Approved once (`session` and `always` count as once).
    Approved,
    /// The user's answer to a clarification, exactly as given.
    Answered(String),
}

/// Why the tool must not continue. [`ApprovalDenial::code`] is the error code
/// the tool returns to the CLI (`isError`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ApprovalDenial {
    UserDenied,
    TimedOut,
    RunCancelled,
    UnattendedRequiresApproval,
    /// The request could not be recorded or settled (storage failure).
    Unavailable(String),
}

impl ApprovalDenial {
    pub fn code(&self) -> &'static str {
        match self {
            Self::UserDenied => "user_denied",
            Self::TimedOut => "approval_timed_out",
            Self::RunCancelled => "run_cancelled",
            Self::UnattendedRequiresApproval => "unattended_requires_approval",
            Self::Unavailable(_) => "approval_unavailable",
        }
    }

    /// A message for the model, in English like the CLI's other tool errors.
    pub fn message(&self) -> String {
        match self {
            Self::UserDenied => "The user denied this action.".into(),
            Self::TimedOut => "Nobody answered the approval request in time.".into(),
            Self::RunCancelled => "The run was cancelled before the user answered.".into(),
            Self::UnattendedRequiresApproval => {
                "This turn runs without a person to approve it, so Clovy refused the action.".into()
            }
            Self::Unavailable(detail) => {
                format!("Clovy could not ask for approval: {detail}")
            }
        }
    }
}

/// Storage and event output of the broker: the app's database and webview
/// in production, an in-memory database and a recorder in tests.
pub trait BrokerIo: Send + Sync + 'static {
    fn pool(&self) -> BoxFuture<'_, Result<SqlitePool, AppError>>;
    /// Emits one runtime event (`interruption.requested` or
    /// `interruption.updated`) for `run_id`.
    fn emit(&self, session_id: &str, run_id: &str, sequence: i64, method: &str, data: Value);
}

/// Time source for the request timeout, replaceable in tests.
pub trait Clock: Send + Sync + 'static {
    fn sleep(&self, duration: Duration) -> BoxFuture<'static, ()>;
}

pub struct TokioClock;

impl Clock for TokioClock {
    fn sleep(&self, duration: Duration) -> BoxFuture<'static, ()> {
        Box::pin(tokio::time::sleep(duration))
    }
}

/// How a request ended, delivered to the waiting tool.
#[derive(Debug)]
enum Settled {
    Approved,
    Denied,
    Answered(String),
    Cancelled,
    Failed(String),
}

struct Waiter {
    session_id: String,
    run_id: String,
    tx: oneshot::Sender<Settled>,
}

struct Inner {
    io: Box<dyn BrokerIo>,
    clock: Box<dyn Clock>,
    timeout: Duration,
    waiters: Mutex<HashMap<String, Waiter>>,
    closing: AtomicBool,
}

/// The broker. Cheap to clone; the app keeps one in Tauri state.
#[derive(Clone)]
pub struct ApprovalBroker {
    inner: Arc<Inner>,
}

impl ApprovalBroker {
    pub fn new(io: impl BrokerIo, clock: impl Clock, timeout: Duration) -> Self {
        Self {
            inner: Arc::new(Inner {
                io: Box::new(io),
                clock: Box::new(clock),
                timeout,
                waiters: Mutex::new(HashMap::new()),
                closing: AtomicBool::new(false),
            }),
        }
    }

    /// Asks the user and waits for the decision (see the module docs).
    pub async fn request(
        &self,
        turn: &ApprovalTurn,
        request: ApprovalRequest,
    ) -> Result<ApprovalOutcome, ApprovalDenial> {
        if !turn.attended {
            tracing::info!(
                run_id = %turn.run_id,
                tool = %request.tool,
                "refused a tool that needs approval in an unattended CLI turn"
            );
            return Err(ApprovalDenial::UnattendedRequiresApproval);
        }
        if self.inner.closing.load(Ordering::Acquire) {
            return Err(ApprovalDenial::RunCancelled);
        }
        let pool = self
            .inner
            .io
            .pool()
            .await
            .map_err(|error| ApprovalDenial::Unavailable(error.message))?;
        let interruption_id = Uuid::new_v4().to_string();
        let interruption = interruption_payload(turn, &request, &interruption_id);
        let clarification = matches!(request.kind, ApprovalKind::Clarification { .. });

        // The waiter exists before the card does, so a decision can never
        // arrive for a request nobody is waiting on.
        let (tx, rx) = oneshot::channel();
        self.lock_waiters().insert(
            interruption_id.clone(),
            Waiter {
                session_id: turn.session_id.clone(),
                run_id: turn.run_id.clone(),
                tx,
            },
        );
        let mut guard = WaitGuard {
            broker: self.clone(),
            interruption_id: interruption_id.clone(),
            armed: true,
        };
        let inserted = match store::insert_pending(&pool, turn, &interruption).await {
            Ok(inserted) => inserted,
            Err(error) => {
                guard.armed = false;
                self.take_waiter(&interruption_id);
                return Err(match error {
                    store::InsertError::RunNotActive => ApprovalDenial::RunCancelled,
                    store::InsertError::Database(error) => {
                        ApprovalDenial::Unavailable(error.to_string())
                    }
                });
            }
        };
        self.inner.io.emit(
            &turn.session_id,
            &turn.run_id,
            inserted.sequence,
            "interruption.requested",
            json!({ "itemId": inserted.external_id, "interruption": inserted.payload }),
        );

        let mut rx = rx;
        let timed_out = tokio::select! {
            settled = &mut rx => Err(settled.unwrap_or(Settled::Cancelled)),
            () = self.inner.clock.sleep(self.inner.timeout) => Ok(()),
        };
        let settled = match timed_out {
            Err(settled) => settled,
            Ok(()) => match self.take_waiter(&interruption_id) {
                Some(waiter) => {
                    guard.armed = false;
                    self.finish(
                        &pool,
                        &waiter,
                        &interruption_id,
                        Settled::Cancelled,
                        store::Settlement::Expired,
                    )
                    .await;
                    return Err(ApprovalDenial::TimedOut);
                }
                // A decision won the race: its owner already holds the
                // sender and always sends after recording it.
                None => rx.await.unwrap_or(Settled::Cancelled),
            },
        };
        guard.armed = false;
        match settled {
            Settled::Approved if !clarification => Ok(ApprovalOutcome::Approved),
            Settled::Answered(answer) if clarification => Ok(ApprovalOutcome::Answered(answer)),
            Settled::Denied => Err(ApprovalDenial::UserDenied),
            Settled::Cancelled => Err(ApprovalDenial::RunCancelled),
            Settled::Failed(detail) => Err(ApprovalDenial::Unavailable(detail)),
            // A resolution of the wrong kind never reaches a waiter
            // (`commands` checks it); fail closed anyway.
            Settled::Approved | Settled::Answered(_) => Err(ApprovalDenial::UserDenied),
        }
    }

    /// Settles every pending request of `run_id` as `run_cancelled` (the run
    /// was cancelled, failed, or completed while a tool was waiting).
    pub async fn cancel_run(&self, run_id: &str) -> usize {
        let waiters = self.take_waiters(|waiter| waiter.run_id == run_id);
        let count = waiters.len();
        self.cancel_taken(waiters).await;
        count
    }

    /// App shutdown: refuses new requests and settles every waiting one as
    /// `run_cancelled`. Items the process cannot record before it exits are
    /// cancelled at the next start ([`store::cancel_stale`]).
    pub fn close(&self) {
        self.inner.closing.store(true, Ordering::Release);
        let waiters = self.take_waiters(|_| true);
        if waiters.is_empty() {
            return;
        }
        let broker = self.clone();
        tauri::async_runtime::spawn(async move { broker.cancel_taken(waiters).await });
    }

    fn take_waiters(&self, matches: impl Fn(&Waiter) -> bool) -> Vec<(String, WaiterRef)> {
        let mut table = self.lock_waiters();
        let ids = table
            .iter()
            .filter(|(_, waiter)| matches(waiter))
            .map(|(id, _)| id.clone())
            .collect::<Vec<_>>();
        ids.into_iter()
            .filter_map(|id| {
                let waiter = table.remove(&id)?;
                Some((id.clone(), WaiterRef::from((id, waiter))))
            })
            .collect()
    }

    async fn cancel_taken(&self, waiters: Vec<(String, WaiterRef)>) {
        if waiters.is_empty() {
            return;
        }
        match self.inner.io.pool().await {
            Ok(pool) => {
                for (id, waiter) in waiters {
                    self.finish(
                        &pool,
                        &waiter,
                        &id,
                        Settled::Cancelled,
                        store::Settlement::Cancelled,
                    )
                    .await;
                }
            }
            Err(error) => {
                tracing::warn!(code = %error.code, "could not record cancelled CLI approvals");
                for (_, waiter) in waiters {
                    waiter.send(Settled::Cancelled);
                }
            }
        }
    }

    /// Whether a tool is waiting on `interruption_id` in this process.
    pub fn is_waiting(&self, interruption_id: &str) -> bool {
        self.lock_waiters().contains_key(interruption_id)
    }

    /// Ids of the requests waiting in this process.
    pub fn waiting_ids(&self) -> Vec<String> {
        self.lock_waiters().keys().cloned().collect()
    }

    /// Applies the user's decision to a waiting request. Errors with
    /// `agent_interruption_expired` when the request is no longer waiting
    /// (already decided, expired, cancelled, or from an earlier process).
    pub(crate) async fn decide(
        &self,
        pool: &SqlitePool,
        interruption_id: &str,
        decision: Decision,
    ) -> Result<(), AppError> {
        let Some(waiter) = self.take_waiter(interruption_id) else {
            return Err(expired_error());
        };
        let (settled, settlement) = match decision {
            Decision::Approve => (Settled::Approved, store::Settlement::Approved),
            Decision::Deny => (Settled::Denied, store::Settlement::Denied),
            Decision::Answer(answer) => (
                Settled::Answered(answer.clone()),
                store::Settlement::Answered(answer),
            ),
        };
        if self
            .finish(pool, &waiter, interruption_id, settled, settlement)
            .await
        {
            Ok(())
        } else {
            Err(AppError::new(
                "agent_interruption_resolution_failed",
                "Clovy could not record this answer. The action was not run.",
            ))
        }
    }

    /// Records the outcome, emits the updated card, and wakes the tool. A
    /// storage failure wakes the tool with a failure instead (fail closed).
    async fn finish(
        &self,
        pool: &SqlitePool,
        waiter: &WaiterRef,
        interruption_id: &str,
        settled: Settled,
        settlement: store::Settlement,
    ) -> bool {
        let recorded = store::settle(pool, &waiter.run_id, interruption_id, &settlement).await;
        // A cancellation stays a cancellation even when it cannot be
        // recorded; any other outcome fails closed.
        let cancelling = matches!(settled, Settled::Cancelled);
        let failed = |detail: String| {
            if cancelling {
                Settled::Cancelled
            } else {
                Settled::Failed(detail)
            }
        };
        let (settled, ok) = match recorded {
            Ok(Some(updated)) => {
                self.inner.io.emit(
                    &waiter.session_id,
                    &waiter.run_id,
                    updated.sequence,
                    "interruption.updated",
                    json!({ "itemId": updated.external_id, "interruption": updated.payload }),
                );
                (settled, true)
            }
            Ok(None) => {
                tracing::warn!(
                    interruption_id,
                    run_id = %waiter.run_id,
                    "a CLI approval left pending before its waiter settled it"
                );
                (failed("the request is no longer pending".into()), false)
            }
            Err(error) => {
                tracing::warn!(%error, interruption_id, "could not record a CLI approval outcome");
                (failed(error.to_string()), false)
            }
        };
        waiter.send(settled);
        ok
    }

    fn take_waiter(&self, interruption_id: &str) -> Option<WaiterRef> {
        self.lock_waiters()
            .remove(interruption_id)
            .map(|waiter| WaiterRef::from((interruption_id.to_string(), waiter)))
    }

    fn lock_waiters(&self) -> std::sync::MutexGuard<'_, HashMap<String, Waiter>> {
        self.inner
            .waiters
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }
}

/// A waiter removed from the table: its owner settles it.
struct WaiterRef {
    session_id: String,
    run_id: String,
    tx: Mutex<Option<oneshot::Sender<Settled>>>,
}

impl WaiterRef {
    fn send(&self, settled: Settled) {
        if let Some(tx) = self
            .tx
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .take()
        {
            let _ = tx.send(settled);
        }
    }
}

impl From<(String, Waiter)> for WaiterRef {
    fn from((_, waiter): (String, Waiter)) -> Self {
        Self {
            session_id: waiter.session_id,
            run_id: waiter.run_id,
            tx: Mutex::new(Some(waiter.tx)),
        }
    }
}

/// The user's answer, validated by [`commands`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum Decision {
    Approve,
    Deny,
    Answer(String),
}

pub(crate) fn expired_error() -> AppError {
    AppError::new(
        "agent_interruption_expired",
        "This interruption can no longer be resumed.",
    )
}

/// Settles the request as cancelled when the waiting tool call goes away
/// (its MCP request was dropped) before anyone decided.
struct WaitGuard {
    broker: ApprovalBroker,
    interruption_id: String,
    armed: bool,
}

impl Drop for WaitGuard {
    fn drop(&mut self) {
        if !self.armed {
            return;
        }
        let Some(waiter) = self.broker.take_waiter(&self.interruption_id) else {
            return;
        };
        let broker = self.broker.clone();
        let interruption_id = std::mem::take(&mut self.interruption_id);
        let Ok(runtime) = tokio::runtime::Handle::try_current() else {
            return;
        };
        runtime.spawn(async move {
            if let Ok(pool) = broker.inner.io.pool().await {
                broker
                    .finish(
                        &pool,
                        &waiter,
                        &interruption_id,
                        Settled::Cancelled,
                        store::Settlement::Cancelled,
                    )
                    .await;
            }
        });
    }
}

/// The item the native engine would record for the same request, generated
/// from app-side data only, plus `engine: "cli"`.
fn interruption_payload(turn: &ApprovalTurn, request: &ApprovalRequest, id: &str) -> Value {
    let created_at = crate::db::repositories::timestamp();
    let mut payload = Map::new();
    payload.insert("id".into(), json!(id));
    payload.insert("sessionId".into(), json!(turn.session_id));
    payload.insert("runId".into(), json!(turn.run_id));
    payload.insert("status".into(), json!("pending"));
    payload.insert("createdAt".into(), json!(created_at));
    payload.insert("engine".into(), json!(CLI_ENGINE));
    payload.insert("cli".into(), json!(turn.cli));
    payload.insert("toolName".into(), json!(request.tool));
    payload.insert("toolCallId".into(), json!(request.call_id));
    match &request.kind {
        ApprovalKind::Approval {
            title,
            description,
            arguments,
            preview,
        } => {
            payload.insert("kind".into(), json!("approval"));
            payload.insert("title".into(), json!(sanitize(title)));
            payload.insert("description".into(), json!(sanitize(description)));
            payload.insert(
                "command".into(),
                json!(approval_command(
                    &request.tool,
                    arguments,
                    preview.as_deref()
                )),
            );
            payload.insert("allowAlways".into(), json!(false));
        }
        ApprovalKind::Clarification { question, choices } => {
            payload.insert("kind".into(), json!("clarification"));
            payload.insert("question".into(), json!(sanitize(question)));
            payload.insert(
                "choices".into(),
                json!(choices
                    .iter()
                    .map(|choice| sanitize(choice))
                    .collect::<Vec<_>>()),
            );
        }
    }
    Value::Object(payload)
}

fn sanitize(value: &str) -> String {
    crate::agent_runtime::host::sanitize_log(value)
}

/// `<tool> <preview>` or `<tool> <arguments>`, secrets redacted.
fn approval_command(tool: &str, arguments: &Value, preview: Option<&str>) -> String {
    let details = match (preview, arguments) {
        (Some(preview), _) => preview.to_string(),
        (None, Value::Object(map)) if map.is_empty() => String::new(),
        (None, Value::Object(map)) => {
            serde_json::to_string_pretty(map).unwrap_or_else(|_| "{}".into())
        }
        (None, Value::Null) => String::new(),
        (None, other) => other.to_string(),
    };
    if details.is_empty() {
        sanitize(tool)
    } else {
        sanitize(&format!("{tool} {details}"))
    }
}

/// Production I/O: the app database and the webview event channel.
struct AppIo {
    app: tauri::AppHandle,
}

impl BrokerIo for AppIo {
    fn pool(&self) -> BoxFuture<'_, Result<SqlitePool, AppError>> {
        Box::pin(async move { Ok(crate::commands::repositories(&self.app).await?.pool) })
    }

    fn emit(&self, session_id: &str, run_id: &str, sequence: i64, method: &str, data: Value) {
        use tauri::Emitter;
        if let Err(error) = self.app.emit(
            crate::agent_runtime::host::AGENT_RUNTIME_EVENT,
            json!({
                "protocolVersion": crate::agent_runtime::protocol::PROTOCOL_VERSION,
                "sessionId": session_id,
                "runId": run_id,
                "sequence": sequence,
                "eventId": Uuid::new_v4().to_string(),
                "method": method,
                "data": data,
            }),
        ) {
            tracing::warn!(%error, run_id, method, "could not emit a CLI approval event");
        }
    }
}

/// Registers the broker in app state, cancels CLI requests a previous
/// process left pending, and settles a run's requests when it ends.
pub fn setup(app: &tauri::App) {
    use tauri::{Listener, Manager};
    let broker = ApprovalBroker::new(
        AppIo {
            app: app.handle().clone(),
        },
        TokioClock,
        APPROVAL_TIMEOUT,
    );
    app.manage(broker.clone());

    let startup = broker.clone();
    tauri::async_runtime::spawn(async move {
        match startup.inner.io.pool().await {
            Ok(pool) => match store::cancel_stale(&pool, &startup.waiting_ids()).await {
                Ok(0) => {}
                Ok(count) => {
                    tracing::info!(count, "cancelled CLI approvals left by a previous run")
                }
                Err(error) => tracing::warn!(%error, "could not cancel stale CLI approvals"),
            },
            Err(error) => {
                tracing::warn!(code = %error.code, "could not open storage to cancel stale CLI approvals")
            }
        }
    });

    // A turn always publishes exactly one terminal event; a request still
    // waiting then can never be answered by its tool.
    let on_end = broker;
    app.listen_any(
        crate::agent_runtime::host::AGENT_RUNTIME_EVENT,
        move |event| {
            // Every streamed delta passes here: skip the parse while no tool
            // waits, which is nearly always.
            if on_end.lock_waiters().is_empty() {
                return;
            }
            let Some(run_id) = terminal_run_id(event.payload()) else {
                return;
            };
            if !on_end
                .lock_waiters()
                .values()
                .any(|waiter| waiter.run_id == run_id)
            {
                return;
            }
            let broker = on_end.clone();
            tauri::async_runtime::spawn(async move {
                broker.cancel_run(&run_id).await;
            });
        },
    );
}

/// App shutdown hook: see [`ApprovalBroker::close`].
pub fn close(app: &tauri::AppHandle) {
    use tauri::Manager;
    if let Some(broker) = app.try_state::<ApprovalBroker>() {
        broker.close();
    }
}

/// The run id of a `run.completed`, `run.cancelled`, or `run.failed` event.
fn terminal_run_id(payload: &str) -> Option<String> {
    let event: Value = serde_json::from_str(payload).ok()?;
    let method = event.get("method")?.as_str()?;
    if !matches!(method, "run.completed" | "run.cancelled" | "run.failed") {
        return None;
    }
    event.get("runId")?.as_str().map(str::to_string)
}
